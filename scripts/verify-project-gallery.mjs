import { chromium } from "playwright";

const baseUrl = process.env.PREVIEW_URL || "http://localhost:3000";
const browser = await chromium.launch({ headless: true, executablePath: "/usr/bin/chromium" });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
await page.goto(`${baseUrl}/projeler`, { waitUntil: "networkidle" });
const triggerCount = await page.locator(".project-comparison__trigger").count();
await page.locator(".project-comparison__trigger").first().click();
const lightboxVisible = await page.locator(".project-lightbox").isVisible();
const firstAlt = await page.locator(".project-lightbox img").getAttribute("alt");
await page.locator(".project-lightbox__nav--right").click();
const secondAlt = await page.locator(".project-lightbox img").getAttribute("alt");
await page.keyboard.press("Escape");
const closedWithEscape = await page.locator(".project-lightbox").count() === 0;
await page.goto(`${baseUrl}/`, { waitUntil: "networkidle" });
const homeProjects = await page.locator("#projeler").count();
const homeProjectCount = await page.locator("#projeler .home-project-card").count();
const homeBeforeAfter = await page.locator("#once-sonra .home-before-after-card").count();
const slider = page.locator("#once-sonra .before-after-slider").first();
const handle = slider.locator('[role="slider"]');
const initialPosition = await handle.getAttribute("aria-valuenow");
await handle.focus();
await page.keyboard.press("ArrowRight");
const keyboardPosition = await handle.getAttribute("aria-valuenow");
const sliderBox = await slider.boundingBox();
if (sliderBox) { await page.mouse.move(sliderBox.x + sliderBox.width * 0.2, sliderBox.y + sliderBox.height / 2); await page.mouse.down(); await page.mouse.move(sliderBox.x + sliderBox.width * 0.78, sliderBox.y + sliderBox.height / 2); await page.mouse.up(); }
const pointerPosition = await handle.getAttribute("aria-valuenow");
const projectHrefs = await page.locator("#projeler .home-project-card").evaluateAll((cards) => cards.map((card) => card.getAttribute("href")));
const beforeAfterHrefs = await page.locator("#once-sonra .home-before-after-card").evaluateAll((cards) => cards.map((card) => card.getAttribute("href")));
const technicalHeading = await page.locator("#teknik-bilgiler .eyebrow").textContent();
console.log(JSON.stringify({ triggerCount, lightboxVisible, firstAlt, secondAlt, closedWithEscape, homeProjects, homeProjectCount, homeBeforeAfter, initialPosition, keyboardPosition, pointerPosition, projectHrefs, beforeAfterHrefs, technicalHeading }));
await browser.close();
